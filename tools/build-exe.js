#!/usr/bin/env node
// Builds dist/MelvorIdle2Companion.exe (or dist/MelvorIdle2Companion elsewhere): one file players can
// double-click, with no Node.js install. Node's single-executable support (--build-sea) wraps this
// Node with a packed copy of the companion; on first run the program unpacks it to
// %LOCALAPPDATA%\MelvorCompanion (once per version) and starts it.
//
//   node tools/build-exe.js
//
// Needs Node 25.5+ for --build-sea. Run it on each system you want a build for: it wraps the Node
// it runs on, so Windows gives MelvorIdle2Companion.exe and macOS/Linux give MelvorIdle2Companion. On macOS it
// signs the result ad hoc (Apple Silicon won't run unsigned programs); for a release, sign it with
// your own certificate as the README describes. Unsigned Windows builds make SmartScreen ask first.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
// What the companion needs at run time; the game data source, tests and tools stay out.
const INCLUDE = ['package.json', 'server', 'engine', 'ui', 'data/companion-data.json', 'data/icons.json'];

function walk(path) {
  const full = join(ROOT, path);
  if (!existsSync(full)) throw new Error(`Missing ${path}. Run "npm run build-data" (and tools/extract-icons.js) first.`);
  if (!statSync(full).isDirectory()) return [path];
  return readdirSync(full).flatMap((name) => walk(join(path, name)));
}

const files = INCLUDE.flatMap(walk).map((p) => p.split('\\').join('/')).sort();
const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const hash = createHash('sha256');
const index = { version, hash: '', files: {} };
const blobs = [];
let offset = 0;
for (const rel of files) {
  const body = readFileSync(join(ROOT, rel));
  hash.update(rel).update(body);
  index.files[rel] = [offset, body.length];
  blobs.push(body);
  offset += body.length;
}
index.hash = hash.digest('hex').slice(0, 12);

// app.pack = u32 index length, the index as JSON, then every file back to back.
const indexBytes = Buffer.from(JSON.stringify(index), 'utf8');
const header = Buffer.alloc(4);
header.writeUInt32LE(indexBytes.length);
rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
writeFileSync(join(DIST, 'app.pack'), Buffer.concat([header, indexBytes, ...blobs]));

// The program's own code: unpack once per version, then start the server from the unpacked copy.
// (Inside a single executable, dynamic import() can't load files, but require() of ES modules can.)
writeFileSync(join(DIST, 'launcher.cjs'), `// Melvor Idle 2 Companion launcher (generated by tools/build-exe.js).
const { getAsset } = require('node:sea');
const { createRequire } = require('node:module');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const pack = Buffer.from(getAsset('app.pack'));
const indexLength = pack.readUInt32LE(0);
const index = JSON.parse(pack.subarray(4, 4 + indexLength).toString('utf8'));
const dataStart = 4 + indexLength;
const base = process.env.LOCALAPPDATA ? path.join(process.env.LOCALAPPDATA, 'MelvorCompanion') : path.join(os.homedir(), '.melvor-companion');
const appDir = path.join(base, 'app-' + index.version + '-' + index.hash);

if (!fs.existsSync(path.join(appDir, '.complete'))) {
  console.log('  Unpacking the companion (first run of this version)...');
  for (const [rel, [offset, size]] of Object.entries(index.files)) {
    const file = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, pack.subarray(dataStart + offset, dataStart + offset + size));
  }
  fs.writeFileSync(path.join(appDir, '.complete'), '');
  // Older versions this program unpacked are no longer needed.
  for (const name of fs.readdirSync(base)) {
    if (name.startsWith('app-') && name !== path.basename(appDir)) fs.rmSync(path.join(base, name), { recursive: true, force: true });
  }
}
process.env.MELVOR_COMPANION_HISTORY ||= path.join(base, 'history');
const entry = path.join(appDir, 'server', 'server.js');
createRequire(entry)(entry);
`);

const exe = process.platform === 'win32' ? 'MelvorIdle2Companion.exe' : 'MelvorIdle2Companion';
writeFileSync(join(DIST, 'sea.json'), JSON.stringify({ main: 'launcher.cjs', output: exe, disableExperimentalSEAWarning: true, assets: { 'app.pack': 'app.pack' } }, null, 2));
execFileSync(process.execPath, ['--build-sea=sea.json'], { cwd: DIST, stdio: 'inherit' });
for (const tmp of ['app.pack', 'launcher.cjs', 'sea.json']) rmSync(join(DIST, tmp));
if (process.platform !== 'win32') chmodSync(join(DIST, exe), 0o755);
if (process.platform === 'darwin') {
  try {
    execFileSync('codesign', ['--force', '--sign', '-', join(DIST, exe)], { stdio: 'inherit' });
  } catch {
    console.warn('Could not sign it (codesign missing?). macOS may refuse to run it until it is signed.');
  }
}

const mb = (n) => `${(n / 1048576).toFixed(0)} MB`;
console.log(`Built ${relative(ROOT, join(DIST, exe))} (${mb(statSync(join(DIST, exe)).size)}): ${files.length} files, companion v${version}.`);
